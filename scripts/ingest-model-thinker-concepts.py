def concept_md(c: dict) -> str:
    part = c["part"]
    rows = "\n".join(
        f"| {label} | [[sources/model-thinker/md/{part}#{anchor}]] |"
        for label, anchor in c["evidence"]
    )
    eb = "\n".join(f"{i}. {q}" for i, q in enumerate(c["explain"], 1))
    return f"""---
domain: model-thinking
origin: zhuomo
mastery: learning
reviewed:
explain_back: not_started
updated: {TODAY}
---

# {c["title"]}

## Claim

{c["claim"]}

## Explain-back

{eb}

## Evidence

| 要点 | 原文 |
|------|------|
{rows}

## Sources

- **Raw:** `{RAW}`
- [[sources/model-thinker]]
"""


def main() -> None:
    concepts_dir = VAULT / "concepts"
    concepts_dir.mkdir(parents=True, exist_ok=True)
    for c in CONCEPTS:
        (concepts_dir / f"{c['slug']}.md").write_text(concept_md(c), encoding="utf-8")
    print(f"Wrote {len(CONCEPTS)} concepts")


if __name__ == "__main__":
    main()
